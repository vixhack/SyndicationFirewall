import subprocess
import urllib.request
import json
import re
import pytest

CANONICAL_ADDRESS = "0xEF723bc4D197fDcDcda32e853783DedDd49429c6"
RPC_URL = "https://studio.genlayer.com/api"


def rpc_call(method: str, params: list):
    payload = {
        "jsonrpc": "2.0",
        "id": 1,
        "method": method,
        "params": params,
    }
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        RPC_URL,
        data=data,
        headers={
            "Content-Type": "application/json",
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) GenLayerIntegration/1.0",
        },
    )
    with urllib.request.urlopen(req, timeout=20) as resp:
        res = json.loads(resp.read().decode("utf-8"))
        if "error" in res:
            raise RuntimeError(f"RPC Error: {res['error']}")
        return res.get("result")


def genlayer_call(method: str, *args):
    """Invoke contract view method via genlayer CLI and parse output."""
    cmd = ["genlayer.cmd", "call", CANONICAL_ADDRESS, method]
    if args:
        cmd.extend(["--args"] + [str(a) for a in args])

    res = subprocess.run(cmd, capture_output=True, text=True, shell=True)
    if res.returncode != 0:
        raise RuntimeError(f"genlayer call failed: {res.stderr}\n{res.stdout}")

    match = re.search(r"Result:\s*\n(.*?)(?:\n\n√|\Z)", res.stdout, re.DOTALL)
    if not match:
        raise ValueError(f"Could not parse result from: {res.stdout}")

    raw = match.group(1).strip()
    if raw == "true":
        return True
    if raw == "false":
        return False
    if raw.isdigit():
        return int(raw)

    # If the output is a JS object representation, parse it into a dict
    if raw.startswith("{") and raw.endswith("}"):
        node_script = "const obj = eval('(' + process.argv[1] + ')'); console.log(JSON.stringify(obj));"
        node_res = subprocess.run(["node", "-e", node_script, raw], capture_output=True, text=True)
        if node_res.returncode == 0:
            return json.loads(node_res.stdout)

    return raw


def test_canonical_contract_schema_on_studionet():
    """Verify the deployed contract exposes the expected method schema on Studionet."""
    schema = rpc_call("gen_getContractSchema", [CANONICAL_ADDRESS])
    assert schema is not None, "Contract schema must exist"
    methods = schema.get("methods", {})

    expected_methods = [
        "submit_content",
        "evaluate_originality",
        "update_canonical_url",
        "archive_submission",
        "get_submission",
        "get_evaluation",
        "latest_verdict",
        "is_cleared",
        "get_submission_count",
        "get_evaluation_count",
    ]
    for m in expected_methods:
        assert m in methods, f"Missing method {m} in deployed Studionet schema"


def test_studionet_submission_state():
    """Verify that submission #1 exists on Studionet and reflects CLEARED status."""
    sub = genlayer_call("get_submission", 1)
    assert isinstance(sub, dict), f"Expected dict for submission, got {type(sub)}"
    assert sub["id"] == 1
    assert sub["submitter"].lower() == "0xb3b09558183aec6c2ff5aa547163b77a9266010a".lower()
    assert sub["title"] == "Decentralized Compute Scaling"
    assert sub["active"] is True
    assert sub["status"] == "CLEARED"
    assert sub["total_evaluations"] == 1


def test_studionet_evaluation_receipt_consensus_evidence():
    """Verify that evaluation receipt #1 was generated by real validator consensus on Studionet."""
    ev = genlayer_call("get_evaluation", 1)
    assert isinstance(ev, dict), f"Expected dict for evaluation, got {type(ev)}"
    assert ev["id"] == 1
    assert ev["submission_id"] == 1
    assert ev["verdict"] == "ORIGINAL"
    assert ev["originality_score"] == 98
    assert ev["is_derivative"] is False
    assert ev["evidence_status_code"] == 200
    assert len(ev["reasoning"]) > 30, "Validator reasoning must be substantive"


def test_studionet_clearance_gate_thresholds():
    """Verify that is_cleared enforces threshold semantics on Studionet."""
    cleared_75 = genlayer_call("is_cleared", 1, 75)
    assert cleared_75 is True, "Originality score 98 must pass threshold 75"

    cleared_99 = genlayer_call("is_cleared", 1, 99)
    assert cleared_99 is False, "Originality score 98 must fail threshold 99"


def test_studionet_counts_consistency():
    """Verify contract counts on Studionet."""
    s_count = genlayer_call("get_submission_count")
    e_count = genlayer_call("get_evaluation_count")
    assert s_count == 1
    assert e_count == 1
